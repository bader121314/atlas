#!/usr/bin/env bash
# Installs and runs the Atlas demo on one Ubuntu server (ADR-062).
#
#   First time:  ./setup.sh            (installs Docker, writes .env, starts)
#   Update:      ./setup.sh update     (pulls the latest code and rebuilds)
#   Demo login:  ./setup.sh password   (prints the shared demo sign-in)
#
# Secrets are generated here, on the server, and never leave it.
set -euo pipefail
cd "$(dirname "$0")"

compose() { sudo docker compose --env-file .env "$@"; }

install_docker() {
  if command -v docker >/dev/null 2>&1; then return; fi
  echo "Installing Docker…"
  sudo apt-get update -y
  sudo apt-get install -y docker.io docker-compose-v2 git curl
  sudo systemctl enable --now docker
}

open_firewall() {
  # Oracle's Ubuntu images block everything but SSH in iptables, in addition
  # to the cloud security list (see the runbook for that part).
  if command -v netfilter-persistent >/dev/null 2>&1; then
    for port in 80 443; do
      if ! sudo iptables -C INPUT -p tcp --dport "$port" -m state --state NEW -j ACCEPT 2>/dev/null; then
        sudo iptables -I INPUT 5 -p tcp --dport "$port" -m state --state NEW -j ACCEPT
      fi
    done
    sudo netfilter-persistent save >/dev/null
  fi
}

secret() { openssl rand -base64 48 | tr -dc 'A-Za-z0-9' | head -c "${1:-40}"; }

write_env() {
  if [ -f .env ]; then return; fi
  local ip="${PUBLIC_IP:-$(curl -fsS https://api.ipify.org)}"
  local dashed="${ip//./-}"
  cat > .env <<ENV
# Generated by setup.sh on $(date -u +%Y-%m-%d). Keep this file private.
APP_HOST=${APP_HOST:-atlas.${dashed}.sslip.io}
FILES_HOST=${FILES_HOST:-files.${dashed}.sslip.io}
POSTGRES_PASSWORD=$(secret 32)
SESSION_SECRET=$(secret 48)
WEBHOOK_SECRET_KEY=$(secret 40)
SSO_SECRET_KEY=$(secret 40)
STORAGE_SECRET_KEY=$(secret 32)
DEMO_PASSWORD=Demo-$(secret 10)
METRICS_TOKEN=$(secret 32)
ENV
  chmod 600 .env
}

show_access() {
  # shellcheck disable=SC1091
  . ./.env
  echo
  echo "Atlas demo: https://${APP_HOST}"
  echo "Demo sign-in: demo@atlas.example / ${DEMO_PASSWORD}"
  echo "(The sign-in page shows it to visitors too.)"
}

case "${1:-start}" in
  start)
    install_docker
    open_firewall
    write_env
    echo "Building and starting (the first build takes 10–20 minutes)…"
    compose up -d --build
    compose logs -f seed || true
    show_access
    ;;
  update)
    git -C ../.. pull --ff-only
    compose up -d --build
    show_access
    ;;
  password)
    show_access
    ;;
  stop)
    compose down
    ;;
  *)
    echo "Usage: ./setup.sh [start|update|password|stop]" >&2
    exit 2
    ;;
esac
